import assert from 'node:assert/strict';
import { before, beforeEach, after, test } from 'node:test';
import mongoose from 'mongoose';
import request from 'supertest';
process.env.NODE_ENV = 'test';
const { createApp } = await import('../src/app.js');
const { connectDB, disconnectDB } = await import('../src/config/db.js');
const { User } = await import('../src/models/User.js');
const { Project } = await import('../src/models/Project.js');
const { Contract } = await import('../src/models/Contract.js');
const { TimeEntry } = await import('../src/models/TimeEntry.js');
const { HourlyInvoice } = await import('../src/models/HourlyInvoice.js');
const { Review } = await import('../src/models/Review.js');
const { FreelancerProfile } = await import('../src/models/FreelancerProfile.js');
const { AuditLog, Dispute, UserReport } = await import('../src/models/Moderation.js');
const { invoiceService, invoiceTotals } = await import('../src/services/invoice.service.js');
const { timeTrackingService } = await import('../src/services/time-tracking.service.js');
const { setSupabaseTokenVerifierForTests } = await import('../src/services/supabase-auth.service.js');
const claims = new Map();
setSupabaseTokenVerifierForTests(async (token) => { if (!claims.has(token)) throw new Error('Invalid'); return claims.get(token); });
const app = createApp();
let client, freelancer, outsider, project, entry, range;
before(async () => connectDB());
after(async () => disconnectDB());
beforeEach(async () => {
  await Promise.all([Review.deleteMany({}), FreelancerProfile.deleteMany({}), HourlyInvoice.deleteMany({}), TimeEntry.deleteMany({}), Project.deleteMany({}), Contract.deleteMany({}), User.deleteMany({})]);
  claims.clear();
  await Promise.all([AuditLog.deleteMany({}), Dispute.deleteMany({}), UserReport.deleteMany({})]);
  [client, freelancer, outsider] = await User.create(['client', 'freelancer', 'outsider'].map((name) => ({ name, email: `${name}@example.test`, role: name === 'client' ? 'client' : 'freelancer', roles: [name === 'client' ? 'client' : 'freelancer'] })));
  const oid = () => new mongoose.Types.ObjectId();
  const contract = await Contract.create({ offer: oid(), acceptedRevision: oid(), proposal: oid(), job: oid(), client: client._id, freelancer: freelancer._id, title: 'Hourly invoice fixture', description: 'A valid hourly agreement for billing integration tests.', budget: { amount: 25, type: 'hourly', currency: 'USD' }, estimatedDays: 20, activatedAt: new Date(Date.now() - 86400000) });
  project = await Project.create({ contract: contract._id, offer: contract.offer, job: contract.job, client: client._id, freelancer: freelancer._id });
  const start = Date.now() - 3 * 3600000;
  entry = await TimeEntry.create({ project: project._id, contract: contract._id, freelancer: freelancer._id, startedAt: new Date(start), endedAt: new Date(start + 3600000), durationMinutes: 60, description: 'Invoice test work', source: 'manual', hourlyRate: 25, estimatedAmount: 25, currency: 'USD', idempotencyKey: 'invoice-test-entry' });
  range = { from: new Date(start - 1000).toISOString(), to: new Date(start + 3601000).toISOString() };
  for (const user of [client, freelancer, outsider]) claims.set(user.name, { sub: `test-${user._id}`, email: user.email, user_metadata: { name: user.name, signup_role: user.role } });
});
test('invoice snapshots preserve rates and lock entries against editing and deletion', async () => {
  const invoice = await invoiceService.create(freelancer, project._id, range);
  assert.equal(invoice.totalCents, 2500);
  assert.equal(invoice.lines[0].hourlyRateCents, 2500);
  assert.equal(String((await TimeEntry.findById(entry._id)).invoice), String(invoice._id));
  await assert.rejects(timeTrackingService.updateEntry(freelancer, project._id, entry._id, { revision: 1, reason: 'Changing work', description: 'Different work' }), /Invoiced/);
  await assert.rejects(timeTrackingService.deleteEntry(freelancer, project._id, entry._id, { revision: 1, reason: 'Removing work' }), /Invoiced/);
});
test('concurrent and repeated invoice requests cannot double bill time', async () => {
  const results = await Promise.allSettled([invoiceService.create(client, project._id, range), invoiceService.create(freelancer, project._id, range)]);
  assert.ok(results.some((r) => r.status === 'fulfilled'));
  assert.equal(await HourlyInvoice.countDocuments({}), 1);
  const retried = await invoiceService.create(client, project._id, range);
  assert.equal(retried.totalMinutes, 60);
  await assert.rejects(invoiceService.create(client, project._id, { from: new Date(new Date(range.from).getTime() - 1000).toISOString(), to: range.to }), /already invoiced|overlaps/);
});
test('invoices reject outsiders, partial periods, future periods, and empty periods', async () => {
  await assert.rejects(invoiceService.list(outsider, project._id), /not found/);
  await assert.rejects(invoiceService.create(outsider, project._id, range), /not found/);
  await assert.rejects(invoiceService.create(client, project._id, { from: entry.startedAt.toISOString(), to: new Date(entry.endedAt.getTime() - 1000).toISOString() }), /complete time entries/);
  await assert.rejects(invoiceService.create(client, project._id, { ...range, to: new Date(Date.now() + 10000).toISOString() }), /closed billing/);
  await assert.rejects(invoiceService.create(client, project._id, { from: new Date(Date.now() - 1000).toISOString(), to: new Date().toISOString() }), /no completed/);
  await request(app).get(`/api/projects/${project._id}/invoices`).expect(401);
});
test('billing uses the historical rate per entry with exact cent rounding', () => {
  const totals = invoiceTotals([{ ...entry.toObject(), hourlyRate: 13.33, durationMinutes: 37 }, { ...entry.toObject(), hourlyRate: 17.29, durationMinutes: 61 }]);
  assert.equal(totals.totalCents, 2580);
  assert.deepEqual(totals.lines.map((l) => l.hourlyRateCents), [1333, 1729]);
});
test('only participants in a completed contract can publish one review and the subject can reply once', async () => {
  const body = { contract: String(project.contract), rating: 5, categories: { communication: 5, quality: 4, reliability: 5 }, title: 'Excellent delivery', comment: 'The freelancer delivered carefully and communicated clearly.' };
  await request(app).post('/api/reviews').set('Authorization', 'Bearer client').send(body).expect(400);
  await Contract.updateOne({ _id: project.contract }, { status: 'completed' });
  await request(app).post('/api/reviews').set('Authorization', 'Bearer outsider').send(body).expect(404);
  const response = await request(app).post('/api/reviews').set('Authorization', 'Bearer client').send(body).expect(201);
  await request(app).post('/api/reviews').set('Authorization', 'Bearer client').send(body).expect(409);
  const path = `/api/reviews/${response.body.data.review._id}/reply`;
  await request(app).post(path).set('Authorization', 'Bearer outsider').send({ text: 'Unrelated reply' }).expect(409);
  await request(app).post(path).set('Authorization', 'Bearer freelancer').send({ text: 'Thank you for the collaboration' }).expect(200);
  await request(app).post(path).set('Authorization', 'Bearer freelancer').send({ text: 'Another reply' }).expect(409);
  await request(app).get(`/api/reviews/profiles/${freelancer._id}`).expect(404);
  await FreelancerProfile.create({ user: freelancer._id, visibility: 'public' });
  const publicReviews = await request(app).get(`/api/reviews/profiles/${freelancer._id}`).expect(200);
  assert.equal(publicReviews.body.data.reputation.rating, 5);
  assert.deepEqual(publicReviews.body.data.reputation.categories, { communication: 5, quality: 4, reliability: 5 });
  assert.equal(publicReviews.body.data.items[0].author.email, undefined);
  await Review.updateOne({ _id: response.body.data.review._id }, { hiddenAt: new Date() });
  const hidden = await request(app).get(`/api/reviews/profiles/${freelancer._id}`).expect(200);
  assert.equal(hidden.body.data.reputation.count, 0);
  assert.deepEqual(hidden.body.data.reputation.categories, { communication: 0, quality: 0, reliability: 0 });
  await User.updateOne({ _id: freelancer._id }, { status: 'suspended' });
  await request(app).get(`/api/reviews/profiles/${freelancer._id}`).expect(404);
});
test('disputes isolate participants and only independent administrators can decide with retained audit', async () => {
  const admin = await User.create({ name: 'Administrator', email: 'admin@example.test', role: 'admin', roles: ['admin'] });
  claims.set('admin', { sub: 'test-admin', email: admin.email, user_metadata: { name: admin.name, signup_role: 'client' } });
  const response = await request(app).post('/api/disputes').set('Authorization', 'Bearer client').send({ contract: String(project.contract), reason: 'The delivered work does not match the agreed requirements.' }).expect(201);
  const path = `/api/disputes/${response.body.data.dispute._id}`;
  await request(app).get(path).set('Authorization', 'Bearer outsider').expect(404);
  await request(app).post(`${path}/decision`).set('Authorization', 'Bearer freelancer').send({ revision: 1, status: 'resolved', reason: 'Participant cannot act as the independent arbitrator.' }).expect(403);
  await request(app).post(`${path}/evidence`).set('Authorization', 'Bearer freelancer').send({ revision: 1, text: 'The delivery includes all the required work and documentation.', links: ['https://example.com/delivery'] }).expect(200);
  await request(app).post(`${path}/decision`).set('Authorization', 'Bearer admin').send({ revision: 2, status: 'resolved', reason: 'Both participants reviewed the evidence and agreed to resolve.' }).expect(200);
  await request(app).post(`${path}/evidence`).set('Authorization', 'Bearer client').send({ revision: 3, text: 'Late response should be blocked after the decision.' }).expect(409);
  assert.equal(await AuditLog.countDocuments({ action: 'dispute_decision' }), 1);
});
test('admin operations reject ordinary users and suspend/reactivate users with atomic audit', async () => {
  await request(app).get('/api/admin/overview').set('Authorization', 'Bearer client').expect(403);
  const admin = await User.create({ name: 'Administrator', email: 'admin@example.test', role: 'admin', roles: ['admin'] });
  claims.set('admin', { sub: 'test-admin', email: admin.email, user_metadata: { name: admin.name, signup_role: 'client' } });
  await request(app).get('/api/admin/overview').set('Authorization', 'Bearer admin').expect(200);
  const path = `/api/admin/users/${freelancer._id}/status`;
  await request(app).post(path).set('Authorization', 'Bearer admin').send({ status: 'suspended', reason: 'Temporarily suspend pending an account review.' }).expect(200);
  await request(app).get('/api/auth/me').set('Authorization', 'Bearer freelancer').expect(401);
  await request(app).post(path).set('Authorization', 'Bearer admin').send({ status: 'active', reason: 'Review completed; restore access to the account.' }).expect(200);
  await request(app).get('/api/auth/me').set('Authorization', 'Bearer freelancer').expect(200);
  assert.equal(await AuditLog.countDocuments({ action: 'user_status' }), 2);
});
