test('agency roles and invitation revocation prevent escalation and serialize acceptance races', async () => {
  const created = await request(app).post('/api/agencies').set(auth('seller')).send({ name: 'Agency control team', description: 'A team for testing consent and membership management safely.', visibility: 'private' }).expect(201);
  const id = created.body.data.agency._id;
  const revision = async () => (await Agency.findById(id)).revision;
  const invite = await request(app).post(`/api/agencies/${id}/invitations`).set(auth('seller')).send({ user: String(outsider._id) }).expect(200);
  await request(app).post(`/api/agencies/invitations/${invite.body.data.invitation._id}/respond`).set(auth('outsider')).send({ decision: 'accept' }).expect(200);
  await request(app).get(`/api/agencies/${id}/invitations`).set(auth('outsider')).expect(403);
  const roleBody = { user: String(outsider._id), action: 'change_role', role: 'manager', revision: await revision() };
  await request(app).post(`/api/agencies/${id}/members`).set(auth('outsider')).send(roleBody).expect(403);
  await request(app).post(`/api/agencies/${id}/members`).set(auth('seller')).send({ ...roleBody, revision: roleBody.revision - 1 }).expect(409);
  await request(app).post(`/api/agencies/${id}/members`).set(auth('seller')).send(roleBody).expect(200);
  assert.equal((await Agency.findById(id)).members.find(m => String(m.user) === String(outsider._id)).role, 'manager');
  await request(app).post(`/api/agencies/${id}/members`).set(auth('outsider')).send({ ...roleBody, role: 'member', revision: await revision() }).expect(403);
  const newcomer = await User.create({ name: 'Newcomer', email: 'newcomer@example.test', role: 'freelancer', roles: ['freelancer'] });
  claims.set('newcomer', { sub: `test-${newcomer._id}`, email: newcomer.email, user_metadata: { name: newcomer.name, signup_role: 'freelancer' } });
  await request(app).post(`/api/agencies/${id}/invitations`).set(auth('outsider')).send({ user: String(newcomer._id), role: 'manager' }).expect(403);
  const pending = await request(app).post(`/api/agencies/${id}/invitations`).set(auth('seller')).send({ user: String(newcomer._id), role: 'manager' }).expect(200);
  const pendingId = pending.body.data.invitation._id;
  const ownerList = await request(app).get(`/api/agencies/${id}/invitations`).set(auth('seller')).expect(200);
  assert.equal(ownerList.body.data.total, 1);
  assert.equal(ownerList.body.data.items[0].invitedUser.email, undefined);
  assert.equal((await request(app).get(`/api/agencies/${id}/invitations`).set(auth('outsider')).expect(200)).body.data.total, 0);
  const revokePath = `/api/agencies/${id}/invitations/${pendingId}/revoke`;
  await request(app).post(revokePath).set(auth('outsider')).send({ revision: await revision() }).expect(403);
  await request(app).post(revokePath).set(auth('seller')).send({ revision: (await revision()) - 1 }).expect(409);
  await request(app).post(revokePath).set(auth('seller')).send({ revision: await revision() }).expect(200);
  await request(app).post(`/api/agencies/invitations/${pendingId}/respond`).set(auth('newcomer')).send({ decision: 'accept' }).expect(409);
  await request(app).post(`/api/agencies/${id}/invitations`).set(auth('outsider')).send({ user: String(newcomer._id), role: 'member' }).expect(200);
  const raceRevision = await revision();
  const raced = await Promise.all([
    request(app).post(revokePath).set(auth('seller')).send({ revision: raceRevision }),
    request(app).post(`/api/agencies/invitations/${pendingId}/respond`).set(auth('newcomer')).send({ decision: 'accept' }),
  ]);
  assert.deepEqual(raced.map(r => r.status).sort(), [200, 409]);
  const finalInvitation = await AgencyInvitation.findById(pendingId);
  const finalAgency = await Agency.findById(id);
  assert.equal(finalAgency.members.some(m => String(m.user) === String(newcomer._id)), finalInvitation.status === 'accepted');
  await request(app).post(`/api/agencies/${id}/members`).set(auth('seller')).send({ user: String(outsider._id), action: 'change_role', role: 'member', revision: await revision() }).expect(200);
  await request(app).get(`/api/agencies/${id}/invitations`).set(auth('outsider')).expect(403);
});

