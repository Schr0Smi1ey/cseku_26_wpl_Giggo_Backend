  assert.equal((await request(app).get('/api/discovery/search?kind=services&q=React').expect(200)).body.data.total, 0);
  await request(app).put('/api/discovery/preferences').set(auth('client')).send({ ...prefs, historyEnabled: false }).expect(200);
