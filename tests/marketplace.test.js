test('security devices are owner-scoped and revoked sessions reject refreshed tokens', async () => {
  const base = claims.get('seller');
  claims.set('seller', { ...base, session_id: 'verified-session-one' });
  claims.set('seller-other', { ...base, session_id: 'verified-session-two' });
  const first = await request(app).get('/api/security').set(auth('seller')).expect(200);
  assert.equal(first.body.data.sessions.length, 1);
  assert.equal(first.body.data.sessions[0].sessionHash, undefined);
  const id = first.body.data.sessions[0]._id;
  await request(app).post(`/api/security/sessions/${id}/revoke`).set(auth('outsider')).expect(404);
  await request(app).post(`/api/security/sessions/${id}/revoke`).set(auth('seller-other')).expect(200);
  await request(app).get('/api/security').set(auth('seller')).expect(401);
  claims.set('seller-refresh', { ...base, session_id: 'verified-session-one', iat: Math.floor(Date.now() / 1000) });
  await request(app).get('/api/auth/me').set(auth('seller-refresh')).expect(401);
  const second = await request(app).get('/api/security').set(auth('seller-other')).expect(200);
  assert.equal(second.body.data.events.filter(e => e.type === 'new_session').length, 2);
});
